import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const files = {
  officerList: "public/documents/officer-list-template.docx",
  enlistedList: "public/documents/enlisted-list-template.docx",
};
const values = Object.fromEntries(Object.entries(files).map(([key, path]) => [
  key,
  readFileSync(resolve(path)).toString("base64"),
]));
const target = resolve("app/generated-list-templates.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `// Generated by scripts/embed-list-templates.mjs.\nexport const LIST_TEMPLATE_BASE64 = ${JSON.stringify(values)} as const;\n`);
